/**
 * Builds the two artifacts this package ships:
 *
 *   lib/client.js    — the plugin bundle, wrapped in DSH's module-loader envelope
 *                      (`window.__ModuleLoader__.load`) with React external.
 *   dev/harness.js   — a standalone page bundling React, used to look at the
 *                      panel without installing the plugin.
 */

import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const watch = process.argv.includes('--watch')

async function buildClient() {
  const result = await build({
    entryPoints: [resolve(root, 'src/client/index.jsx')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'transform',
    external: ['react', 'react-dom'],
    write: false,
    legalComments: 'none',
    logLevel: 'info',
  })

  const code = result.outputFiles[0].text
  const wrapped = `/* ${pkg.name} ${pkg.version} — generated by scripts/build-client.mjs */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
${code}
    return module.exports
  }
})
`
  await mkdir(resolve(root, 'lib'), { recursive: true })
  await writeFile(resolve(root, 'lib/client.js'), wrapped, 'utf8')
  console.log(`• lib/client.js  ${(wrapped.length / 1024).toFixed(1)} KB`)
}

async function buildHarness() {
  await mkdir(resolve(root, 'dev'), { recursive: true })
  await build({
    entryPoints: [resolve(root, 'dev/harness.jsx')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'transform',
    outfile: resolve(root, 'dev/harness.js'),
    legalComments: 'none',
    logLevel: 'info',
  })
  console.log('• dev/harness.js')
}

await buildClient()
if (process.argv.includes('--with-harness')) await buildHarness()
else if (watch) {
  // Dev loop: rebuild the client bundle, then the harness.
  await buildHarness()
}
